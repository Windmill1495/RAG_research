"""Signed experiment checkpoints, separate from the retrieval index cache.

One RunCache has one writer. A failed sample is still a completed sample: resume
does not silently rerun it or change the fixed evaluation denominator.
"""
from __future__ import annotations

import hashlib
import json
import os
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable


def _json(value) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":"), allow_nan=False)


def make_signature(value) -> str:
    """Hash the actual identity values, not a filename or a sample ID alone."""
    return hashlib.sha256(_json(value).encode("utf-8")).hexdigest()


def file_sha256(path: Path | str) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def code_hashes(project_root: Path | str, paths: Iterable[Path | str] | None = None) -> dict[str, str]:
    """Fingerprint local runtime/evaluation code; omit generated bytecode."""
    root = Path(project_root).resolve()
    candidates = ([*root.glob("*.py"), *(root / "rag").rglob("*.py")]
                  if paths is None else [Path(path) for path in paths])
    result = {}
    for path in candidates:
        path = (path if path.is_absolute() else root / path).resolve()
        if not path.is_relative_to(root):
            raise ValueError("代码签名文件必须位于项目目录内")
        if path.is_file():
            result[path.relative_to(root).as_posix()] = file_sha256(path)
    return dict(sorted(result.items()))


class RunCache:
    """Create a new signed run, or resume exactly the same experiment identity.

    identity should include task, model and generation options, visible-history
    rules, dataset/corpus hashes, strategies, and code/prompt hashes. Absolute
    paths need not be identity values if the files are identified by content.
    """

    def __init__(self, output_dir: Path | str, identity: dict, *, resume: bool = False):
        if not isinstance(identity, dict) or not identity:
            raise ValueError("实验 identity 必须是非空字典")
        # Store a JSON snapshot so later caller mutation cannot change identity.
        self.identity = json.loads(_json(identity))
        self.signature = make_signature(self.identity)
        self.output_dir = Path(output_dir)
        self.manifest_path = self.output_dir / "manifest.json"
        self.checkpoint_path = self.output_dir / "checkpoint.jsonl"
        self.rows: list[dict] = []
        self.completed_keys: set[str] = set()
        self._lock = threading.Lock()
        if resume:
            if not self.output_dir.is_dir():
                raise ValueError("续跑目录不存在；首次运行请不要使用 --resume")
            try:
                self.manifest = json.loads(self.manifest_path.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                raise ValueError("续跑目录缺少有效 manifest.json") from exc
            if (self.manifest.get("version") != 1
                    or self.manifest.get("signature") != self.signature
                    or self.manifest.get("identity") != self.identity
                    or make_signature(self.manifest.get("identity")) != self.signature):
                raise ValueError("实验签名不匹配：模型、数据、提示词/代码或配置已改变；请使用新的输出目录")
            self._restore()
        else:
            self.output_dir.mkdir(parents=True, exist_ok=False)
            self.manifest = {
                "version": 1, "signature": self.signature, "identity": self.identity,
                "created_at_utc": datetime.now(timezone.utc).isoformat(),
                "resume_policy": "Only matching identities; recorded errors are completed and are not silently retried.",
            }
            self.manifest_path.write_text(json.dumps(self.manifest, ensure_ascii=False, indent=2), encoding="utf-8")
            self.checkpoint_path.touch(exist_ok=False)

    def _restore(self) -> None:
        if not self.checkpoint_path.is_file():
            raise ValueError("续跑目录缺少 checkpoint.jsonl，不能推测哪些样本已完成")
        raw = self.checkpoint_path.read_bytes()
        lines = raw.splitlines(keepends=True)
        valid_end = 0
        discard_tail = False
        needs_newline = False
        for index, line in enumerate(lines):
            last = index == len(lines) - 1
            try:
                row = json.loads(line.decode("utf-8"))
            except (UnicodeError, ValueError) as exc:
                # Only an interrupted, unterminated last write may be discarded.
                if last and not line.endswith(b"\n"):
                    discard_tail = True
                    break
                raise ValueError(f"checkpoint 第 {index + 1} 行损坏，拒绝不明确的恢复") from exc
            if not isinstance(row, dict) or not isinstance(row.get("cache_key"), str) or not row["cache_key"]:
                raise ValueError(f"checkpoint 第 {index + 1} 行缺少有效 cache_key")
            if row["cache_key"] in self.completed_keys:
                raise ValueError("checkpoint 出现重复 cache_key，拒绝重复计分")
            self.rows.append(row)
            self.completed_keys.add(row["cache_key"])
            valid_end += len(line)
            needs_newline = last and not line.endswith(b"\n")
        if discard_tail:
            with self.checkpoint_path.open("r+b") as handle:
                handle.truncate(valid_end)
                handle.flush()
                os.fsync(handle.fileno())
        elif needs_newline:
            with self.checkpoint_path.open("ab") as handle:
                handle.write(b"\n")
                handle.flush()
                os.fsync(handle.fileno())

    def append(self, row: dict, key: str) -> None:
        if not isinstance(row, dict) or not isinstance(key, str) or not key:
            raise ValueError("checkpoint 需要字典记录和非空字符串 key")
        if "cache_key" in row and row["cache_key"] != key:
            raise ValueError("记录的 cache_key 与指定 key 不一致")
        stored = {**row, "cache_key": key}
        data = (_json(stored) + "\n").encode("utf-8")
        with self._lock:
            if key in self.completed_keys:
                raise ValueError(f"样本 {key} 已有记录，不可重复追加；失败记录也不自动重试")
            with self.checkpoint_path.open("ab") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
            self.rows.append(json.loads(data))
            self.completed_keys.add(key)
